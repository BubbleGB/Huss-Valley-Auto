return function(Core)
    local n=0
    local function check(ok,message)assert(ok,message);n=n+1 end
    local base={MaxSpeed=40,Acceleration=50,Deceleration=65,StallSpeedCap=7,
        Dash=table.freeze({Distance=12,Duration=.28,Cooldown=1.1})}
    local fast=Core.scaleSpeedProfile(base,1.05,true)
    check(fast.MaxSpeed==42 and fast.Acceleration>=100000,'ordinary movement must reach its current cap in one model step')
    check(fast.Deceleration==65 and fast.Dash==base.Dash,'instant acceleration must retain native stops and dash behavior')
    check(base.Acceleration==50,'must not mutate cached native profiles')
    local state=Core.smartSpeedStep(nil,10,true,true,12,1)
    check(math.abs(state.untilAt-10.4)<1e-8 and state.readyAt==22,'close opponent must start a 0.4-second burst with a 12-second cooldown')
    check(Core.effectiveSpeed(1.05,true,state,10.2)==1.10,'burst must be 1.10x total, not stacked')
    check(Core.effectiveSpeed(1.5,true,state,10.2)==1.5,'smart mode must not compound or lower a higher manual setting')
    check(Core.effectiveSpeed(1.05,false,state,10.2)==1.05,'toggle off must cancel boost immediately')
    check(Core.effectiveSpeed(1,true,state,10.2,1.05)==1.05,'learned server limit must reduce future bursts')
    check(Core.effectiveSpeed(1,true,state,10.2,2)==1.10,'smart cap must never exceed 1.10x even with an invalid learned limit')
    state=Core.smartSpeedStep(state,10.4,true,true,10,1)
    check(Core.effectiveSpeed(1.05,true,state,10.4)==1.05,'remaining nearby must not extend the burst beyond 0.4 seconds')
    check(state.watchUntil>13,'correction monitoring must continue after a short burst expires')
    local delayed=Core.smartSpeedStep(state,12,true,true,10,1,true)
    check(delayed.untilAt==0 and delayed.readyAt>=27 and delayed.watchUntil==0,'delayed correction must cancel its observation window and back off')
    local early=Core.smartSpeedStep(state,11,true,true,21,1)
    early=Core.smartSpeedStep(early,12,true,true,5,1)
    check(early.untilAt==0,'separating and reentering must not bypass the 12-second cooldown')
    state=Core.smartSpeedStep(state,30,true,true,10,1)
    check(state.untilAt<=30,'remaining nearby must not repeatedly rearm a burst')
    state=Core.smartSpeedStep(state,31,true,true,21,1)
    state=Core.smartSpeedStep(state,32,true,true,10,1)
    check(math.abs(state.untilAt-32.4)<1e-8,'leaving and reentering the proximity band may rearm after cooldown')
    state=Core.smartSpeedStep(state,33,false,true,10,1)
    check(state.untilAt==0 and state.readyAt>=44,'disabling must cancel without erasing cooldown')
    state=Core.smartSpeedStep(state,34,true,false,5,1)
    check(state.untilAt==0,'inactive/safe/stunned actors must not get smart bursts')
    state=Core.smartSpeedStep(state,35,true,true,5,2)
    check(state.untilAt==0 and state.readyAt>=44,'round/character changes must not bypass the cooldown')
    state=Core.smartSpeedStep(state,45,true,true,5,2)
    check(math.abs(state.untilAt-45.4)<1e-8,'new context may burst once the shared cooldown ends')
    state=Core.smartSpeedStep(state,45.2,true,true,5,2,true)
    check(state.untilAt==0 and state.readyAt>=60.2,'a same-round correction must cancel and back off the burst')
    check(Core.smartLimit({jobId='a',cap=1.05},'a')==1.10,'old three-second policy limits must not prevent the authorized short-burst trial')
    check(Core.smartLimit({jobId='a',policy=Core.SMART_POLICY,cap=1.05},'a')==1.05,'new-policy fallback must survive reloads on the same server')
    check(Core.smartLimit({jobId='a',policy=Core.SMART_POLICY,cap=1.05},'b')==1.10,'a different server starts the new trial peak')
    local charge=Core.closeCharge(Vector3.new(8,0,0),function()return true end)
    check(charge and charge.X>.99,'nearby runner must get direct pursuit')
    check(not Core.closeCharge(Vector3.new(8,0,0),function()return false end),'close pursuit must not override walls/traps')
    check(not Core.closeCharge(Vector3.new(20,0,0),function()return true end),'distant runners retain interception')
    check(not Core.closeCharge(Vector3.new(8,8,0),function()return true end),'must not charge through vertical separation')
    local farHidden={id=1,position=Vector3.new(40,0,0),invisible=true}
    local closeVisible={id=2,position=Vector3.new(9,0,0)}
    check(Core.selectChaseTarget({farHidden,closeVisible},1,Vector3.zero).id==2,'a close catching opportunity must outrank a distant pursuit')
    local closeHidden={id=3,position=Vector3.new(11,0,0),invisible=true}
    check(Core.selectChaseTarget({closeVisible,closeHidden},2,Vector3.zero).id==3,'invisibility priority must still apply among close opportunities')
    local race=Core.racePressure(4,{{state='Safe'},{state='Active',eta=2},{state='Active',eta=3},{state='Active',eta=6},{state='Waiting'}})
    check(race.total==6 and race.targetPlace==3 and race.projectedPlace==4 and race.urgency>=.85,'falling behind the front half must raise pacing urgency')
    race=Core.racePressure(2,{{state='Active',eta=4},{state='Active',eta=6},{state='Caught'}})
    check(race.total==3 and race.projectedPlace==1 and race.urgency>=.2 and race.urgency<.7,'leading runners should make progress without unnecessary all-out risk')
    check(Core.racePressure(2,{}).urgency==0,'a solo runner has no relative finish-rank objective')
    local policy=Core.runnerPolicy(100,60,40,1000000,40,1,10,0,0,nil,0,.9)
    check(policy.urgency>=.9,'finish-rank pressure must reach the actual runner strategy')
    local choice={enabled=true,inMatch=true,phase='HeroChoice',role='Runner',id=1,selectedId=1,now=10,endsAt=20,chasers=5}
    local action,value=Core.choiceAction(choice,{},1)
    check(action=='HeroChoice'and value=='Hero','five or fewer chasers must select Hero')
    choice.chasers=6;action,value=Core.choiceAction(choice,{},1)
    check(value=='Chicken','more than five chasers must select Chicken')
    choice.chasers=nil;action,value=Core.choiceAction(choice,{},1)
    check(value=='Chicken','unknown chaser count must conservatively choose Chicken')
    return {passed=n}
end
