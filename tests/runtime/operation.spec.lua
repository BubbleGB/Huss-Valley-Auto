return function(source)
 local first=assert(source:find('local function createOperationStatus(',1,true),'operation status factory missing')
 local last=assert(source:find('runner.operation=createOperationStatus',first,true))
 local factory=assert(loadstring(source:sub(first,last-1)..'\nreturn createOperationStatus'))()
 local now=10
 local op=factory(function()return now end,function(id)return id=='Cloak'and'Cloak'or id end)
 op:Base('Crossing','crossing')
 assert(op:Read(true,true).description=='Crossing','base operation')
 op:Set('progression','Spinning',15,'spinning',nil,'spin')
 assert(op:Read(true,false).description=='Spinning','lobby work overrides waiting')
 assert(op:Read(true,true).description=='Crossing','lobby work not shown in match')
 op:Set('avoidance','Evading PlayerA',.5,'evading','PlayerA')
 local r=op:Read(true,true);assert(r.action=='evading'and r.target=='PlayerA','specific fresh evasion')
 r.description='bad';assert(op:Read(true,true).description=='Evading PlayerA','report copy')
 assert(op:Read(false,true).description=='Stopped','stopped always overrides pending work')
 now=11;assert(op:Read(true,true).description=='Crossing','expired evasion clears')
 local dive={kind='Dive',id='d1',requestedClock=11,operationTarget='PlayerB'};op:Action(dive,'requesting')
 assert(op:Read(true,true).description:find('Diving at PlayerB',1,true),'dive identifies actual target')
 op:Action(dive,'rejected')
 assert(op:Read(true,true).description=='Crossing','rejection does not linger as active action')
 local cloak={kind='Ability:Cloak',id='a1',requestedClock=11};op:Action(cloak,'requesting');op:Action(cloak,'active')
 assert(op:Read(true,true).description=='Using Cloak','owned ability named')
 local old={kind='Melee',id='old',requestedClock=11,operationTarget='Old'};op:Action(old,'requesting')
 now=12;op:Action({kind='Melee',id='new',requestedClock=12,operationTarget='New'},'requesting')
 op:Action(old,'confirmed')
 assert(op:Read(true,true).target=='New','late old replies cannot replace newer operation')
 op:Reset();op:Action(old,'confirmed');assert(op:Read(true,true).action=='waiting','reset rejects late replies from previous running session')
 return {priority='passed',stopped='passed',expiry='passed',targets='passed',replies='passed',isolation='passed'}
end
