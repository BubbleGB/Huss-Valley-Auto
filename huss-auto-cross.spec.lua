-- Run against the real planner in a Roblox client (Vector3/CFrame required).
return function(Core)
    assert(type(Core) == 'table', 'automatic crossing planner is missing')
    local count = 0
    local function check(value, message)
        assert(value, message)
        count = count + 1
    end
    local origin, goal = Vector3.zero, Vector3.new(0, 0, 100)
    local function choose(threats, allowed)
        return Core.choose(origin, goal, 30, threats or {}, allowed or function() return true end, Vector3.zero)
    end
    local d = choose()
    check(d.Z > 0.99, 'clear crossing should go forward')
    d = choose({{position=Vector3.new(0,0,18),velocity=Vector3.zero,radius=9}})
    check(math.abs(d.X) > 0.3 or d.Z < 0, 'must avoid running straight into a catcher')
    d = choose({{position=Vector3.new(25,0,15),velocity=Vector3.new(-50,0,0),radius=9}})
    check(d.Z < 0.99, 'must anticipate a catcher moving across our route')
    d = choose({}, function(v) return v.X < -0.5 end)
    check(d.X < -0.5, 'must reject directions blocked by map geometry')
    d = choose({}, function() return false end)
    check(d.Magnitude == 0, 'must stop when all routes have missing ground or obstacles')
    d = choose({}, function(v) return v.Z < -0.9 end)
    check(d.Z < -0.9, 'must retreat out of a dead end instead of waiting forever')
    check(Core.canRun(true,true,'Runner','Active',false,false), 'active runner should cross')
    check(not Core.canRun(false,true,'Runner','Active',false,false), 'Stop must prevent movement')
    check(not Core.canRun(true,true,'Catcher','Active',false,false), 'catchers must not be controlled')
    check(not Core.canRun(true,true,'Runner','Safe',false,false), 'safe runner must wait')
    check(not Core.canRun(true,true,'Runner','Caught',false,false), 'caught runner must wait')
    check(not Core.canRun(true,true,'Runner','Active',true,false), 'locked character must wait')
    check(not Core.canRun(true,true,'Runner','Active',false,true), 'map changes must stop movement')
    local p = Core.zoneGoal(CFrame.new(0,10,100),Vector3.new(40,20,20),Vector3.new(50,3,0))
    check(p.X <= 16 and p.Z >= 94, 'goal must stay inside the safe zone')
    check(p.Y == 3, 'safe zone height must not create an airborne target')
    check(Core.probeDistance(5,30) == 5, 'must not reject a finish because floor ends beyond the goal')
    check(Core.probeDistance(100,30) == 12, 'probe must look ahead far enough to stop at obstacles')
    check(Core.canHunt(true,true,'Catcher','Active',false,false), 'active catcher should hunt')
    check(not Core.canHunt(true,true,'Runner','Active',false,false), 'hunt must not control runners')
    check(not Core.canHunt(false,true,'Catcher','Active',false,false), 'Stop must prevent hunting')
    check(not Core.canHunt(true,true,'Catcher','Active',true,false), 'locked catcher must wait')
    check(not Core.canHunt(true,true,'Catcher','Active',false,true), 'hunt must stop during map changes')
    check(Core.isRunner(true,'Runner','Active',100,false), 'active runner is a valid target')
    check(not Core.isRunner(true,'Runner','Safe',100,false), 'crossed runners must be released')
    check(not Core.isRunner(true,'Runner','Caught',100,false), 'caught runners must be released')
    check(not Core.isRunner(true,'Runner','Active',0,false), 'dead runners must be released')
    check(not Core.isRunner(false,'Runner','Active',100,false), 'lobby runners must not be hunted')
    local function runner(id,distance)
        return {id=id,position=Vector3.new(distance,0,0)}
    end
    local current, rival = runner(1,100),runner(2,85)
    check(Core.selectRunner({current,rival},nil,origin).id==2, 'initial target must be nearest')
    check(Core.selectRunner({current,rival},1,origin).id==1, 'must retain target when rival is only slightly closer')
    rival=runner(2,60)
    check(Core.selectRunner({current,rival},1,origin).id==2, 'must switch when rival is much closer')
    check(Core.selectRunner({rival},1,origin).id==2, 'must reacquire when current target crossed or left')
    check(Core.selectRunner({},1,origin)==nil, 'must release target when no active runners remain')
    check(Core.selectRunner({runner(1,6),runner(2,3)},1,origin).id==1, 'must not flicker targets within catching distance')
    local function attack(relative,velocity,meleeReady,diveReady,clear)
        return Core.combatAction(relative,velocity or Vector3.zero,Vector3.zero,
            12,0.35,5.5,5.25,meleeReady~=false,diveReady~=false,clear~=false)
    end
    check(attack(Vector3.new(0,0,4))=='Melee', 'must prefer melee within commit range')
    check(attack(Vector3.new(0,0,10))==nil, 'must keep pursuing instead of attempting a long dive')
    check(attack(Vector3.new(0,0,6.5))==nil, 'must not dive without running momentum')
    local function closeDive(targetVelocity,ownVelocity,distance)
        return Core.combatAction(Vector3.new(0,0,distance or 6.5),targetVelocity,ownVelocity,
            15,0.32,5.5,5.25,true,true,true)
    end
    check(closeDive(Vector3.new(0,0,34),Vector3.new(0,0,33))~='Dive', 'alignment alone cannot authorize a dive without native catch prediction')
    check(closeDive(Vector3.new(12,0,34),Vector3.new(0,0,33))==nil, 'must preserve movement when runner is strafing')
    check(closeDive(Vector3.new(0,0,34),Vector3.new(30,0,5))==nil, 'must not dive while turning toward target')
    check(closeDive(Vector3.new(0,0,15),Vector3.new(0,0,33))~='Dive', 'must prefer pursuit or melee when melee range is quickly reachable')
    check(closeDive(Vector3.new(0,0,34),Vector3.new(0,0,33),9)==nil, 'must reject dives with too much dodge time')
    check(attack(Vector3.new(0,0,40))==nil, 'must not waste dives on distant runners')
    check(attack(Vector3.new(0,0,10),Vector3.new(0,0,70))==nil, 'must not dive when runner outruns its reach')
    check(attack(Vector3.new(0,0,10),nil,true,true,false)==nil, 'must not dive into an obstacle')
    check(attack(Vector3.new(0,0,4),nil,false,false)==nil, 'must honor melee and dive cooldowns')
    check(attack(Vector3.new(0,10,4))==nil, 'must not attack a target on a different vertical level')
    local _, aim=attack(Vector3.new(0,0,4),Vector3.new(10,0,0))
    check(aim.X>0, 'melee aim must lead a moving target')
    check(Core.shouldDash(Vector3.xAxis,Vector3.new(0,0,30),100,true,true), 'must dash on a clear running turn')
    check(not Core.shouldDash(Vector3.zAxis,Vector3.new(0,0,30),100,true,true), 'straight running must not spam dash')
    check(not Core.shouldDash(Vector3.xAxis,Vector3.zero,100,true,true), 'dash requires running momentum')
    check(not Core.shouldDash(Vector3.xAxis,Vector3.new(0,0,30),100,false,true), 'dash must honor cooldown')
    check(not Core.shouldDash(Vector3.xAxis,Vector3.new(0,0,30),100,true,false), 'dash must not cross blocked ground')
    check(not Core.shouldDash(Vector3.xAxis,Vector3.new(0,0,30),3,true,true), 'must not dash beyond finish')
    check(not Core.combatReady(10.15,10.85,10,0.85,0.7), 'must not dive during a locally started melee')
    check(not Core.combatReady(10.5,0,10,0.85,0), 'must honor server melee recovery after reloading')
    check(not Core.combatReady(11,0,10,0.85,0.2), 'must honor active local prediction cooldown')
    check(Core.combatReady(11,10.85,10,0.85,0), 'attacks may resume once all melee clocks are ready')
    check(not Core.canCommitDive(11,14,1), 'must keep pursuing during the extra dive commitment cooldown')
    check(not Core.canCommitDive(15,14,0.1), 'must observe a new or turning target before committing')
    check(Core.canCommitDive(15,14,0.6), 'may commit after cooldown and stable target observation')
    local history
    for i,speed in ipairs({10,15,20,25,30,34}) do
        history=Core.trackMotion(history,1,Vector3.new(0,0,speed),i*0.1)
    end
    check(not Core.canCommitDive(15,14,0.6-history.stableSince), 'gradual acceleration must not qualify as stable motion')
    history=Core.trackMotion(history,2,Vector3.new(0,0,34),0.7)
    check(history.stableSince==0.7, 'changing target must restart motion observation')
    return {passed=count}
end
